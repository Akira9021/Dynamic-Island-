object Lang {
    enum class Mode { RU, EN, ID }

    val mode: Mode
        get() = when (SettingsRepo.current.language) {
            AppLanguage.EN -> Mode.EN
            AppLanguage.RU -> Mode.RU
            AppLanguage.ID -> Mode.ID
            AppLanguage.SYSTEM -> when (systemLanguage()) {
                "ru" -> Mode.RU
                "id", "in" -> Mode.ID
                else -> Mode.EN
            }
        }

    val en: Boolean get() = mode == Mode.EN

    val locale: Locale
        get() = when (mode) {
            Mode.RU -> Locale.forLanguageTag("ru")
            Mode.ID -> Locale.forLanguageTag("id")
            else -> Locale.ENGLISH
        }

    private fun systemLanguage(): String =
        runCatching { Resources.getSystem().configuration.locales[0].language }.getOrNull() ?: Locale.getDefault().language
}

